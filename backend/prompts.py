def format_context(chunks: list[dict]) -> str:
    """Format retrieved chunks into a source-bounded context block.

    Args:
        chunks: Retrieved paper chunks with page and paragraph metadata.

    Returns:
        A numbered context string used by the generator.
    """
    formatted_blocks = []
    for index, chunk in enumerate(chunks, start=1):
        formatted_blocks.append(
            "\n".join(
                [
                    f"【论文片段 {index}】",
                    f"页码：{chunk.get('page')}",
                    f"段落：{chunk.get('block_id')}",
                    f"节点类型：{chunk.get('node_type', 'paragraph')}",
                    f"章节：{chunk.get('section', 'Unknown')}",
                    f"论文文件：{chunk.get('filename', '')}",
                    "原文：",
                    chunk.get("text", ""),
                ]
            )
        )
    return "\n\n".join(formatted_blocks)
